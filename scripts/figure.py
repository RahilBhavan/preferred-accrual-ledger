"""Generate the README figure and a responsive result table from actual reconciliation checks."""
import sys
from decimal import Decimal
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from ledger.reconcile import run  # noqa: E402


def main():
    checks = run()
    groups = [('Quarterly cash totals', checks[1:9]),
              ('Weekly funding comparisons', checks[9:]),
              ('Conditional daily-table total', checks[:1])]
    matched = sum(c.within for c in checks)
    svg = ['<svg xmlns="http://www.w3.org/2000/svg" width="900" height="530" viewBox="0 0 900 530" role="img" aria-labelledby="title desc">',
           f'<title id="title">{matched} of {len(checks)} checks within rounding tolerance</title>',
           '<desc id="desc">Quarterly cash totals: 6 of 8; weekly funding: 4 of 7; conditional daily total: 1 of 1. Five differences remain unresolved. Funding is not settlement. Financial cutoff October 21, 2026.</desc>',
           '<rect width="900" height="530" fill="#F5F5EF"/>',
           '<g fill="#111214" font-family="IBM Plex Sans, sans-serif">',
           '<text x="36" y="53" font-size="23">RAHIL BHAVAN · PREFERRED ACCRUAL LEDGER</text>',
           f'<text x="36" y="112" font-size="42">{matched} of {len(checks)} checks within rounding</text>',
           '<text x="36" y="159" font-size="29">Five gaps remain: two FX and three funding comparisons.</text>']
    for i, (name, subset) in enumerate(groups):
        y = 235 + 66 * i
        svg += [f'<text x="36" y="{y}" font-size="31">{escape(name)}</text>',
                f'<text x="840" y="{y}" text-anchor="end" font-size="34">{sum(c.within for c in subset)} / {len(subset)}</text>']
    svg += ['<text x="36" y="423" font-size="25">Funding comparisons do not establish settlement.</text>',
            '<text x="36" y="466" font-size="21" fill="#52545A">As of 2026-10-21 · SEC filings + ECB FX · ledger/reconcile.py</text>',
            '<text x="36" y="499" font-size="21" fill="#52545A">Daily terms are conditional; the October 28 vote is pending at cutoff.</text>',
            '</g></svg>']
    (ROOT / 'docs/reconciliation.svg').write_text('\n'.join(svg) + '\n')
    rows = []
    labels = ('STRE Q1 2026 cash dividends', 'STRE Q2 2026 cash dividends',
              'STRC dividend funding · Aug 10–16',
              'Preferred dividend and debt interest funding · Sep 14–20 (STRC model)',
              'Preferred dividend funding · Oct 12–18 (STRC model)')
    for c in checks:
        if c.within:
            continue
        scale = Decimal(1000) if c.unit == 'USD thousands' else Decimal(1)
        fmt = lambda x: format(x / scale, 'f').rstrip('0').rstrip('.') if '.' in format(x / scale, 'f') else str(x / scale)
        rows.append(f'<tr><th scope="row">{escape(labels[len(rows)])}</th>'
                    f'<td data-label="Reported">{fmt(c.reported)}</td>'
                    f'<td data-label="Model sensitivity">{fmt(c.ledger_low) if c.ledger_low == c.ledger_high else fmt(c.ledger_low) + "–" + fmt(c.ledger_high)}</td></tr>')
    html = '''<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Preferred ledger reconciliation gaps</title><style>
body{margin:0;color:#111214;background:#F5F5EF;font:18px/1.5 "IBM Plex Sans",Arial,sans-serif}
h1{font-size:32px;line-height:1.15;margin:0 0 16px}p{margin:12px 0}table{border-collapse:collapse;width:100%;font-variant-numeric:tabular-nums}
td,th{text-align:right;padding:14px 8px;border-bottom:1px solid #C6C7BF}th:first-child{text-align:left}thead{font-size:16px}tbody th{font-weight:400}a{color:inherit}
@media(max-width:600px){table,tbody{display:block;width:100%}thead{display:none}th,td{overflow-wrap:anywhere}tr{display:block;padding:14px 0;border-bottom:1px solid #C6C7BF}td,th{display:block;border:0;padding:3px 0;text-align:left}td:before{content:attr(data-label) ": ";color:#52545A}h1{font-size:28px}}
</style><h1>11 of 16 checks agree within rounding.<br>Five gaps remain.</h1>
<p>Frozen financial cutoff: October 21, 2026. All values below are USD millions. Ranges vary weekly share dating; they are not guaranteed bounds.</p>
<table><thead><tr><th>Comparison</th><th>Reported</th><th>Model sensitivity</th></tr></thead><tbody>'''
    html += ''.join(rows) + '''</tbody></table><p>Funding is not settlement. September includes unmodeled debt interest; STRE uses ECB reference FX rather than observed company conversion rates.</p>
<p>Daily terms remain an explicit approval scenario. The October 28 vote was pending at the snapshot.</p>
<p>Sources: <a href="https://www.sec.gov/Archives/edgar/data/1050446/000105044626000044/mstr-20260630.htm">June 10-Q</a> and weekly SEC filings through October 19. Generated by ledger/reconcile.py; exact source links and assumptions accompany every check in reconciliation.json.</p></html>'''
    (ROOT / 'docs/result.html').write_text(html + '\n')
    print('Generated docs/reconciliation.svg and docs/result.html from 16 checks')


if __name__ == '__main__':
    main()
